// zlive template compiler: .html templates with @props/@zig/@if/@for/
// @children/@Name directives -> Zig source rendering zlive segment trees.
//
// The generated code is plain Zig that the real compiler type-checks —
// that is where expression/props type verification happens; this compiler
// only parses structure, never Zig.
//
// Template format: header directives, then markup.
//
//   @zig {
//   pub const Variant = enum { primary, danger };
//   }
//   @props {
//       label: []const u8,
//       variant: Variant = .primary,
//   }
//
//   <button class="btn btn-{@tagName(props.variant)}">{props.label}</button>
//   @if (props.open) {
//   <div>shown</div>
//   } @else {
//   <div>hidden</div>
//   }
//   @for (props.items) |item| {
//   <li>{item}</li>
//   }
//
// Whitespace rule: text is verbatim except that a line break is dropped
// when the preceding text ends with '>' and the next line starts with '<'
// (templates can be written multi-line without introducing whitespace
// text nodes between elements). Directive lines leave no text behind.
//
// Escaping rule: a `{props.x}` / `{item.y}` substitution is *text* — the
// client HTML-escapes it ({"s": ...} on the wire). An inline `{if ...}`
// chooses between the template author's own literals — attribute
// fragments, class names — which are markup by construction and emitted
// raw ({"html": ...}). An inline if must therefore never select between
// prop values that carry text.

const std = @import("std");

pub const Error = error{
    OutOfMemory,
    WriteFailed,
    MissingProps,
    UnexpectedDirective,
    UnexpectedElse,
    UnclosedBlock,
    StrayClose,
    UnbalancedBraces,
    UnbalancedExpr,
};

pub const Node = union(enum) {
    text: []const u8,
    expr: []const u8,
    children, // @children
    splice: []const u8, // @children (expr) — splice an arbitrary segment list
    component: Component,
    if_block: IfBlock,
    for_block: ForBlock,

    pub const Component = struct { name: []const u8, args: []const u8 };
    pub const IfBlock = struct { cond: []const u8, then_nodes: []Node, else_nodes: []Node };
    pub const ForBlock = struct { clause: []const u8, body: []Node };
};

const max_block_depth = 32;

const FrameKind = enum { root, if_then, if_else, for_loop };

const Frame = struct {
    kind: FrameKind,
    clause: []const u8 = "",
    nodes: std.ArrayListUnmanaged(Node) = .empty,
    else_nodes: std.ArrayListUnmanaged(Node) = .empty,
};

/// Compiles a template to Zig source. Caller owns the result.
pub fn compileSource(allocator: std.mem.Allocator, source: []const u8, name: []const u8) Error![]u8 {
    var p = Parser{ .allocator = allocator, .source = source };
    const tmpl = try p.parse();

    var out: std.Io.Writer.Allocating = .init(allocator);
    defer out.deinit();
    const w = &out.writer;

    try w.print("// Generated by zlive-compile from {s} — do not edit.\n", .{name});
    try w.writeAll("const std = @import(\"std\");\n");
    try w.writeAll("const zlive = @import(\"zlive\");\n");
    try w.writeAll("const Segment = zlive.Segment;\n\n");
    for (tmpl.zig_blocks) |block| {
        try w.writeAll(block);
        try w.writeAll("\n\n");
    }
    try w.writeAll("pub const Props = struct {");
    if (tmpl.props) |props| try w.writeAll(props);
    try w.writeAll("};\n\n");
    try w.writeAll("pub fn render(allocator: std.mem.Allocator, props: Props) ![]Segment {\n");
    try w.writeAll("    var _segs: std.ArrayListUnmanaged(Segment) = .empty;\n");
    try w.writeAll("    errdefer _segs.deinit(allocator);\n");
    var counter: usize = 0;
    try emitNodes(w, tmpl.body, "_segs", 1, &counter);
    try w.writeAll("    return _segs.toOwnedSlice(allocator);\n}\n");
    return out.toOwnedSlice();
}

const Template = struct {
    props: ?[]const u8,
    zig_blocks: []const []const u8,
    body: []Node,
};

const Parser = struct {
    allocator: std.mem.Allocator,
    source: []const u8,

    fn parse(self: *Parser) Error!Template {
        var pos: usize = 0;
        var props: ?[]const u8 = null;
        var zig_blocks: std.ArrayListUnmanaged([]const u8) = .empty;

        // Header: @zig / @props blocks and whitespace, in any order.
        while (true) {
            pos = skipWhitespaceLines(self.source, pos);
            if (matchKeyword(self.source, pos, "@zig")) {
                const block = try readBraceBlock(self.source, pos + "@zig".len);
                try zig_blocks.append(self.allocator, block.inner);
                pos = block.end;
                continue;
            }
            if (matchKeyword(self.source, pos, "@props")) {
                const block = try readBraceBlock(self.source, pos + "@props".len);
                props = block.inner;
                pos = block.end;
                continue;
            }
            break;
        }
        if (props == null) return error.MissingProps;

        const body = try self.parseBody(self.source[pos..]);
        return .{ .props = props, .zig_blocks = zig_blocks.items, .body = body };
    }

    fn parseBody(self: *Parser, body: []const u8) Error![]Node {
        var stack: [max_block_depth]Frame = undefined;
        var depth: usize = 0;
        stack[0] = .{ .kind = .root };

        var text: std.ArrayListUnmanaged(u8) = .empty;
        defer text.deinit(self.allocator);

        var lines = Lines{ .rest = body };
        while (lines.next()) |line| {
            const trimmed = std.mem.trim(u8, line, " \t\r");
            if (std.mem.eql(u8, trimmed, "}")) {
                try self.flushText(&stack, depth, &text);
                if (depth == 0) return error.StrayClose;
                const frame = &stack[depth];
                const node: Node = switch (frame.kind) {
                    .if_then, .if_else => .{ .if_block = .{
                        .cond = frame.clause,
                        .then_nodes = frame.nodes.items,
                        .else_nodes = frame.else_nodes.items,
                    } },
                    .for_loop => .{ .for_block = .{
                        .clause = frame.clause,
                        .body = frame.nodes.items,
                    } },
                    .root => unreachable,
                };
                depth -= 1;
                try self.currentList(&stack, depth).append(self.allocator, node);
                continue;
            }
            if (std.mem.eql(u8, trimmed, "@else {") or std.mem.eql(u8, trimmed, "} @else {")) {
                if (depth == 0 or stack[depth].kind != .if_then) return error.UnexpectedElse;
                try self.flushText(&stack, depth, &text);
                stack[depth].kind = .if_else;
                continue;
            }
            if (directiveKeyword(trimmed, "@if")) {
                try self.flushText(&stack, depth, &text);
                if (depth + 1 >= max_block_depth) return error.UnclosedBlock;
                depth += 1;
                stack[depth] = .{ .kind = .if_then, .clause = try clauseOf(trimmed, "@if") };
                continue;
            }
            if (directiveKeyword(trimmed, "@for")) {
                try self.flushText(&stack, depth, &text);
                if (depth + 1 >= max_block_depth) return error.UnclosedBlock;
                depth += 1;
                stack[depth] = .{ .kind = .for_loop, .clause = try clauseOf(trimmed, "@for") };
                continue;
            }
            if (directiveKeyword(trimmed, "@children")) {
                try self.flushText(&stack, depth, &text);
                const rest = std.mem.trim(u8, trimmed["@children".len..], " \t");
                if (rest.len == 0) {
                    try self.currentList(&stack, depth).append(self.allocator, .children);
                } else {
                    try self.currentList(&stack, depth).append(self.allocator, .{ .splice = rest });
                }
                continue;
            }
            if (trimmed.len > 1 and trimmed[0] == '@' and std.ascii.isAlphabetic(trimmed[1])) {
                try self.flushText(&stack, depth, &text);
                const node = try parseComponentCall(trimmed);
                try self.currentList(&stack, depth).append(self.allocator, node);
                continue;
            }
            try self.parseTextLine(&stack, depth, &text, line);
        }
        try self.flushText(&stack, 0, &text);
        if (depth != 0) return error.UnclosedBlock;
        return stack[0].nodes.items;
    }

    fn currentList(self: *Parser, stack: *[max_block_depth]Frame, depth: usize) *std.ArrayListUnmanaged(Node) {
        _ = self;
        const frame = &stack[depth];
        return if (frame.kind == .if_else) &frame.else_nodes else &frame.nodes;
    }

    fn flushText(self: *Parser, stack: *[max_block_depth]Frame, depth: usize, text: *std.ArrayListUnmanaged(u8)) Error!void {
        if (text.items.len == 0) return;
        try self.currentList(stack, depth).append(self.allocator, .{ .text = text.items });
        text.* = .empty;
    }

    // Parses one markup line into the pending text buffer / node list,
    // handling inline {expr} segments and the '>'/'<' line-join rule.
    fn parseTextLine(self: *Parser, stack: *[max_block_depth]Frame, depth: usize, text: *std.ArrayListUnmanaged(u8), line: []const u8) Error!void {
        var rest = line;
        while (true) {
            const open = std.mem.indexOfScalar(u8, rest, '{') orelse break;
            if (open + 1 < rest.len and rest[open + 1] == '{') {
                // {{ escape: literal brace
                try self.appendText(text, rest[0 .. open + 1]);
                rest = rest[open + 2 ..];
                continue;
            }
            try self.appendText(text, rest[0..open]);
            try self.flushText(stack, depth, text);
            const close = try scanExpr(rest, open);
            const expr = std.mem.trim(u8, rest[open + 1 .. close], " \t");
            try self.currentList(stack, depth).append(self.allocator, .{ .expr = expr });
            rest = rest[close + 1 ..];
        }
        if (rest.len == 0) return;
        try self.appendText(text, rest);
    }

    // The join rule: a line break between lines is dropped when the buffer
    // ends with '>' and the incoming line starts (after whitespace) with
    // '<'; any other boundary inserts a '\n'.
    fn appendText(self: *Parser, text: *std.ArrayListUnmanaged(u8), piece: []const u8) Error!void {
        if (piece.len == 0) return;
        if (text.items.len > 0) {
            const trimmed = std.mem.trimStart(u8, piece, " \t");
            if (text.items[text.items.len - 1] == '>' and trimmed.len > 0 and trimmed[0] == '<') {
                try text.appendSlice(self.allocator, trimmed);
                return;
            }
            try text.append(self.allocator, '\n');
        }
        try text.appendSlice(self.allocator, piece);
    }
};

const Lines = struct {
    rest: []const u8,

    fn next(self: *Lines) ?[]const u8 {
        if (self.rest.len == 0) return null;
        const nl = std.mem.indexOfScalar(u8, self.rest, '\n');
        if (nl) |i| {
            const line = self.rest[0..i];
            self.rest = self.rest[i + 1 ..];
            return line;
        }
        const line = self.rest;
        self.rest = "";
        return line;
    }
};

fn matchKeyword(source: []const u8, pos: usize, kw: []const u8) bool {
    if (!std.mem.startsWith(u8, source[pos..], kw)) return false;
    const after = pos + kw.len;
    return after >= source.len or source[after] == ' ' or source[after] == '\t' or
        source[after] == '\r' or source[after] == '\n' or source[after] == '{';
}

/// Skips whitespace INCLUDING newlines; returns the position of the next
/// non-whitespace byte (header directives start at line starts by
/// construction since we only skip whole whitespace runs).
fn skipWhitespaceLines(source: []const u8, start: usize) usize {
    var pos = start;
    while (pos < source.len) : (pos += 1) {
        switch (source[pos]) {
            ' ', '\t', '\r', '\n' => {},
            else => return pos,
        }
    }
    return pos;
}

const BraceBlock = struct { inner: []const u8, end: usize };

/// Reads a `{ ... }` block starting at or after `pos`; the content between
/// the outer braces is returned, `end` is just past the closing brace.
/// Strings and char literals are skipped so braces inside them don't count.
fn readBraceBlock(source: []const u8, pos: usize) Error!BraceBlock {
    const open = std.mem.indexOfScalarPos(u8, source, pos, '{') orelse
        return error.UnbalancedBraces;
    var depth: usize = 0;
    var i = open;
    while (i < source.len) : (i += 1) {
        const c = source[i];
        switch (c) {
            '"' => i = skipString(source, i) orelse return error.UnbalancedBraces,
            '\'' => i = skipCharLiteral(source, i) orelse return error.UnbalancedBraces,
            '/' => if (i + 1 < source.len and source[i + 1] == '/') {
                i = std.mem.indexOfScalarPos(u8, source, i, '\n') orelse source.len - 1;
            },
            '{' => depth += 1,
            '}' => {
                depth -= 1;
                if (depth == 0) return .{ .inner = source[open + 1 .. i], .end = i + 1 };
            },
            else => {},
        }
    }
    return error.UnbalancedBraces;
}

/// Scans an inline `{expr}` starting at `open` (the '{'); returns the index
/// of the matching '}'. Balances (){}[] and skips string/char literals.
fn scanExpr(line: []const u8, open: usize) Error!usize {
    var depth: usize = 0;
    var i = open;
    while (i < line.len) : (i += 1) {
        const c = line[i];
        switch (c) {
            '"' => i = skipString(line, i) orelse return error.UnbalancedExpr,
            '\'' => i = skipCharLiteral(line, i) orelse return error.UnbalancedExpr,
            // '/' cannot start a line comment here: exprs are single-line
            '{', '(', '[' => depth += 1,
            '}', ')', ']' => {
                depth -= 1;
                if (depth == 0) {
                    if (c != '}') return error.UnbalancedExpr;
                    return i;
                }
            },
            else => {},
        }
    }
    return error.UnbalancedExpr;
}

fn skipString(src: []const u8, start: usize) ?usize {
    var i = start + 1;
    while (i < src.len) : (i += 1) {
        if (src[i] == '\\') {
            i += 1;
        } else if (src[i] == '"') return i;
    }
    return null;
}

fn skipCharLiteral(src: []const u8, start: usize) ?usize {
    var i = start + 1;
    while (i < src.len) : (i += 1) {
        if (src[i] == '\\') {
            i += 1;
        } else if (src[i] == '\'') return i;
    }
    return null;
}

fn directiveKeyword(line: []const u8, kw: []const u8) bool {
    return std.mem.startsWith(u8, line, kw) and
        (line.len == kw.len or line[kw.len] == ' ' or line[kw.len] == '(');
}

/// Extracts the clause between the keyword and the trailing '{':
/// "@if (props.open) {" -> "(props.open)".
fn clauseOf(line: []const u8, kw: []const u8) Error![]const u8 {
    if (!std.mem.endsWith(u8, line, "{")) return error.UnexpectedDirective;
    const mid = std.mem.trim(u8, line[kw.len .. line.len - 1], " \t");
    if (mid.len == 0) return error.UnexpectedDirective;
    return mid;
}

/// Parses "@Name(args)" (single line; args end at the line's final ')').
fn parseComponentCall(line: []const u8) Error!Node {
    const call = line[1..];
    const open = std.mem.indexOfScalar(u8, call, '(') orelse
        return error.UnexpectedDirective;
    if (!std.mem.endsWith(u8, call, ")")) return error.UnexpectedDirective;
    const name = std.mem.trim(u8, call[0..open], " \t");
    if (name.len == 0) return error.UnexpectedDirective;
    return .{ .component = .{
        .name = name,
        .args = call[open + 1 .. call.len - 1],
    } };
}

/// Inline conditional: `{if (cond) "a" else "b"}`. Its branches are the
/// template author's own literals — markup by construction, so the segment
/// is emitted as raw HTML (Segment.html), not as escapable text.
fn isInlineIf(e: []const u8) bool {
    return std.mem.startsWith(u8, e, "if ") or std.mem.startsWith(u8, e, "if(");
}

fn emitNodes(w: anytype, nodes: []const Node, target: []const u8, indent: usize, counter: *usize) Error!void {    for (nodes) |node| {
        switch (node) {
            .text => |t| {
                if (t.len == 0) continue;
                try writeIndent(w, indent);
                try w.print("try {s}.append(allocator, .text(\"", .{target});
                try writeEscaped(w, t);
                try w.writeAll("\"));\n");
            },
            .expr => |e| {
                try writeIndent(w, indent);
                // Escaping class: an inline {if ...} chooses between the
                // template author's own literals (attribute fragments,
                // class names) — markup by construction, emitted raw.
                // Every other expression ({props.x}, {item.y}) is data and
                // is HTML-escaped by the client ({"s": ...} on the wire).
                if (isInlineIf(e)) {
                    try w.print("try {s}.append(allocator, .html({s}));\n", .{ target, e });
                } else {
                    try w.print("try {s}.append(allocator, .of({s}));\n", .{ target, e });
                }
            },
            .children => {
                try writeIndent(w, indent);
                try w.print("try {s}.append(allocator, .{{ .children = props.children }});\n", .{target});
            },
            .splice => |e| {
                try writeIndent(w, indent);
                try w.print("try {s}.append(allocator, .{{ .children = {s} }});\n", .{ target, e });
            },
            .component => |c| {
                try writeIndent(w, indent);
                try w.print("try {s}.append(allocator, .{{ .children = try zlive.renderChild(allocator, {s}, @as({s}.Props, {s})) }});\n", .{ target, c.name, c.name, c.args });
            },
            .if_block => |b| {
                const k = counter.*;
                counter.* += 1;
                var name_buf: [32]u8 = undefined;
                const bname = std.fmt.bufPrint(&name_buf, "_b{d}", .{k}) catch unreachable;
                try writeIndent(w, indent);
                try w.writeAll("{\n");
                try writeIndent(w, indent + 1);
                try w.print("var {s}: std.ArrayListUnmanaged(Segment) = .empty;\n", .{bname});
                try writeIndent(w, indent + 1);
                try w.print("if {s} {{\n", .{b.cond});
                try emitNodes(w, b.then_nodes, bname, indent + 2, counter);
                if (b.else_nodes.len > 0) {
                    try writeIndent(w, indent + 1);
                    try w.writeAll("} else {\n");
                    try emitNodes(w, b.else_nodes, bname, indent + 2, counter);
                }
                try writeIndent(w, indent + 1);
                try w.writeAll("}\n");
                try writeIndent(w, indent + 1);
                try w.print("try {s}.append(allocator, .{{ .children = try {s}.toOwnedSlice(allocator) }});\n", .{ target, bname });
                try writeIndent(w, indent);
                try w.writeAll("}\n");
            },
            .for_block => |b| {
                const k = counter.*;
                counter.* += 1;
                var name_buf: [32]u8 = undefined;
                const bname = std.fmt.bufPrint(&name_buf, "_b{d}", .{k}) catch unreachable;
                var iname_buf: [32]u8 = undefined;
                const iname = std.fmt.bufPrint(&iname_buf, "_i{d}", .{k}) catch unreachable;
                try writeIndent(w, indent);
                try w.writeAll("{\n");
                try writeIndent(w, indent + 1);
                try w.print("var {s}: std.ArrayListUnmanaged(Segment) = .empty;\n", .{bname});
                try writeIndent(w, indent + 1);
                try w.print("for {s} {{\n", .{b.clause});
                try writeIndent(w, indent + 2);
                try w.print("var {s}: std.ArrayListUnmanaged(Segment) = .empty;\n", .{iname});
                try emitNodes(w, b.body, iname, indent + 3, counter);
                try writeIndent(w, indent + 2);
                try w.print("try {s}.append(allocator, .{{ .children = try {s}.toOwnedSlice(allocator) }});\n", .{ bname, iname });
                try writeIndent(w, indent + 1);
                try w.writeAll("}\n");
                try writeIndent(w, indent + 1);
                try w.print("try {s}.append(allocator, .{{ .children = try {s}.toOwnedSlice(allocator) }});\n", .{ target, bname });
                try writeIndent(w, indent);
                try w.writeAll("}\n");
            },
        }
    }
}

fn writeIndent(w: anytype, indent: usize) !void {
    try w.splatByteAll(' ', indent * 4);
}

fn writeEscaped(w: anytype, text: []const u8) !void {
    for (text) |c| {
        switch (c) {
            '"' => try w.writeAll("\\\""),
            '\\' => try w.writeAll("\\\\"),
            '\n' => try w.writeAll("\\n"),
            '\t' => try w.writeAll("\\t"),
            '\r' => try w.writeAll("\\r"),
            else => if (c < 0x20) {
                try w.print("\\x{x:0>2}", .{c});
            } else {
                try w.writeByte(c);
            },
        }
    }
}

