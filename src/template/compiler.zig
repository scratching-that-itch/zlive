fn expectCompiled(source: []const u8, expected_fragment: []const u8) !void {
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    const zig = try compileSource(arena.allocator(), source, "test.html");
    if (std.mem.indexOf(u8, zig, expected_fragment) == null) {
        std.debug.print("--- generated ---\n{s}\n--- expected fragment ---\n{s}\n", .{ zig, expected_fragment });
        return error.TestExpectedFragment;
    }
}

test "props block and a simple interpolation" {
    try expectCompiled(
        \\@props {
        \\    label: []const u8,
        \\}
        \\
        \\<button>{props.label}</button>
    ,
        \\pub const Props = struct {
        \\    label: []const u8,
        \\};
    );
    try expectCompiled(
        \\@props {
        \\    label: []const u8,
        \\}
        \\<button>{props.label}</button>
    ,
        \\try _segs.append(allocator, .of(props.label));
    );
    try expectCompiled(
        \\@props {
        \\    label: []const u8,
        \\}
        \\<button>{props.label}</button>
    ,
        \\try _segs.append(allocator, .text("<button>"));
    );
}

